export const actorRoles = [
  "invited_guest",
  "guest",
  "user",
  "creator",
  "operator",
  "reviewer",
  "admin",
] as const;

export type ActorRole = (typeof actorRoles)[number];

type ReadSemantics = Readonly<{ kind: "read" }>;
type CommandSemantics = Readonly<{
  kind: "command";
  idempotencyKey: true;
  concurrency?: "if-match";
}>;
type DeterministicResourceSemantics = Readonly<{
  kind: "deterministic-resource-key";
  resourceKey: "id" | "listingId";
}>;

export interface M1OperationRegistration {
  readonly apiId: string;
  readonly operationId: string;
  readonly method: "GET" | "POST" | "PUT" | "DELETE";
  readonly path: string;
  readonly capId: string;
  readonly action: string;
  readonly permission:
    | "Invited Guest"
    | "Guest"
    | "User"
    | "Public"
    | "Public/Owner"
    | "Reviewer"
    | "Owner";
  readonly roles: readonly ActorRole[];
  readonly mutation:
    ReadSemantics | CommandSemantics | DeterministicResourceSemantics;
  readonly contract:
    | "auth"
    | "instrument"
    | "feed-watchlist"
    | "content-social"
    | "notification-moderation"
    | "portfolio";
}

