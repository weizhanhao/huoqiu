import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { approvedEventTypes } from "@huoqiu/contracts/events";
import { m1OperationRegistry } from "@huoqiu/contracts/m1";
import { describe, expect, it } from "vitest";

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const repoRoot = fileURLToPath(new URL("../../..", import.meta.url));
const generatorPath = join(packageRoot, "scripts/generate.mts");
const tsxPath = join(repoRoot, "node_modules/.bin/tsx");

interface GeneratedManifest {
  readonly api_ids: readonly string[];
  readonly contract_version: string;
  readonly event_types: readonly string[];
  readonly oracle_sha256: Readonly<{
    api_operations: string;
    event_types: string;
  }>;
}

const runGenerator = (args: readonly string[]): string =>
  execFileSync(tsxPath, [generatorPath, ...args], {
    cwd: repoRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });

const readOptionalFile = (path: string): string | undefined =>
  existsSync(path) ? readFileSync(path, "utf8") : undefined;

const restoreOptionalFile = (
  path: string,
  source: string | undefined,
): void => {
  if (source === undefined) {
    rmSync(path, { force: true });
    return;
  }
  writeFileSync(path, source, "utf8");
};

describe("M1 SDK generator", () => {
  it("provides the deterministic generator entrypoint", () => {
    expect(existsSync(`${packageRoot}/scripts/generate.mts`)).toBe(true);
  });

  it("generates the approved 31 API and 18 event manifest from public sources", () => {
    const candidateDirectory = mkdtempSync(join(tmpdir(), "huoqiu-sdk-test-"));

    try {
      runGenerator(["--output", candidateDirectory]);

      const typesPath = join(candidateDirectory, "src/types.ts");
      const manifestPath = join(candidateDirectory, "generated-manifest.json");
      expect(existsSync(typesPath)).toBe(true);
      expect(existsSync(manifestPath)).toBe(true);

      const typesSource = readFileSync(typesPath, "utf8");
      const manifestSource = readFileSync(manifestPath, "utf8");
      const manifest = JSON.parse(manifestSource) as GeneratedManifest;

      expect(manifest).toEqual({
        api_ids: m1OperationRegistry.map(({ apiId }) => apiId),
        contract_version: "m1.v1",
        event_types: approvedEventTypes,
        oracle_sha256: {
          api_operations:
            "f97b4b41f03f1731d47058b36bcc8551869161ca6331e647b03c3683a20a759d",
          event_types:
            "b43899ba72e8e3b70d6f3bb8f99e4769719db38907f0dd9a6ea97a33329c2331",
        },
      });
      expect(manifest.api_ids).toHaveLength(31);
      expect(new Set(manifest.api_ids).size).toBe(31);
      expect(manifest.event_types).toHaveLength(18);
      expect(new Set(manifest.event_types).size).toBe(18);
      expect(typesSource).toContain(
        'import type { AppRouter } from "@huoqiu/contracts/m1";',
      );
      expect(typesSource).toContain(
        'import { approvedEventTypes } from "@huoqiu/contracts/events";',
      );
      expect(typesSource).not.toMatch(
        /(?:generated[_-]?at|timestamp|\/Users\/|[A-Za-z]:\\)/u,
      );
      expect(manifestSource).not.toMatch(
        /(?:generated[_-]?at|timestamp|\/Users\/|[A-Za-z]:\\)/u,
      );
    } finally {
      rmSync(candidateDirectory, { force: true, recursive: true });
    }
  });

  it("installs only verified candidates and checks regenerated bytes", () => {
    const candidateDirectory = mkdtempSync(join(tmpdir(), "huoqiu-sdk-test-"));
    const installedTypesPath = join(packageRoot, "src/types.ts");
    const installedManifestPath = join(packageRoot, "generated-manifest.json");
    const previousTypes = readOptionalFile(installedTypesPath);
    const previousManifest = readOptionalFile(installedManifestPath);

    try {
      runGenerator(["--output", candidateDirectory]);
      writeFileSync(installedTypesPath, "// stale generated output\n", "utf8");
      expect(() => runGenerator(["--check"])).toThrow();

      const installOutput = runGenerator([
        "--install-from",
        candidateDirectory,
      ]);
      expect(installOutput).toContain("SDK_GENERATION_INSTALL PASS");
      expect(readFileSync(installedTypesPath, "utf8")).toBe(
        readFileSync(join(candidateDirectory, "src/types.ts"), "utf8"),
      );
      expect(readFileSync(installedManifestPath, "utf8")).toBe(
        readFileSync(
          join(candidateDirectory, "generated-manifest.json"),
          "utf8",
        ),
      );
      expect(runGenerator(["--check"])).toContain("SDK_GENERATION_CHECK PASS");

      writeFileSync(installedTypesPath, "// tampered\n", "utf8");
      expect(() => runGenerator(["--check"])).toThrow();
      writeFileSync(
        installedTypesPath,
        readFileSync(join(candidateDirectory, "src/types.ts"), "utf8"),
        "utf8",
      );

      writeFileSync(
        join(candidateDirectory, "generated-manifest.json"),
        '{"tampered":true}\n',
        "utf8",
      );
      expect(() =>
        runGenerator(["--install-from", candidateDirectory]),
      ).toThrow();
      expect(readFileSync(installedManifestPath, "utf8")).not.toContain(
        "tampered",
      );
    } finally {
      restoreOptionalFile(installedTypesPath, previousTypes);
      restoreOptionalFile(installedManifestPath, previousManifest);
      rmSync(candidateDirectory, { force: true, recursive: true });
    }
  });
});
